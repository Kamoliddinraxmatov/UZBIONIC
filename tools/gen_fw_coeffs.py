"""Generate firmware/include/uzb_coeffs.h from the Python reference filter design.

Usage: python tools/gen_fw_coeffs.py [fs_hz]   (default 2000)
Re-run whenever the sample rate or filter parameters in emg/pipeline change.
"""

import sys
from pathlib import Path

from scipy import signal as sps

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from emg.pipeline import PipelineConfig  # noqa: E402


def _section(b0, b1, b2, a1, a2):
    return f"    {{{b0:.10e}f, {b1:.10e}f, {b2:.10e}f, {a1:.10e}f, {a2:.10e}f}},"


def main(fs: float = 2000.0) -> None:
    cfg = PipelineConfig()
    bp = sps.butter(4, (cfg.low_hz, cfg.high_hz), btype="bandpass", fs=fs, output="sos")
    b, a = sps.iirnotch(cfg.notch_hz, 30.0, fs=fs)
    lines = [
        "/* Generated by tools/gen_fw_coeffs.py — do not edit by hand. */",
        "#ifndef UZB_COEFFS_H",
        "#define UZB_COEFFS_H",
        "",
        f"#define UZB_FS_HZ {fs:.1f}f",
        f"#define UZB_BP_SECTIONS {len(bp)}",
        f"#define UZB_WINDOW_SAMPLES {int(round(cfg.window_ms * fs / 1000.0))}",
        f"#define UZB_MIN_ON_SAMPLES {int(round(cfg.min_on_ms * fs / 1000.0))}",
        f"#define UZB_MIN_OFF_SAMPLES {int(round(cfg.min_off_ms * fs / 1000.0))}",
        "",
        "/* {b0, b1, b2, a1, a2}, a0 normalised to 1 */",
        f"static const float UZB_BP_COEFFS[UZB_BP_SECTIONS][5] = {{",
        *[_section(s[0], s[1], s[2], s[4], s[5]) for s in bp],
        "};",
        "",
        "static const float UZB_NOTCH_COEFFS[5] =",
        _section(b[0] / a[0], b[1] / a[0], b[2] / a[0], a[1] / a[0], a[2] / a[0]).rstrip(",").replace("    ", "    ", 1) + ";",
        "",
        "#endif",
        "",
    ]
    out = ROOT / "firmware" / "include" / "uzb_coeffs.h"
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main(*map(float, sys.argv[1:]))
